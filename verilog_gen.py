"""Binding + Verilog emission (datapath, mux network, FSM controller, testbench)."""
import random
from collections import defaultdict
from frontend import is_const

PFX = {'+': 'add', '-': 'sub', '*': 'mul'}
MOD = {'+': 'hls_adder', '-': 'hls_subtractor', '*': 'hls_multiplier'}
COMMUTATIVE = {'+', '*'}
MAXSW = 16            # 4 select switches -> 16 entries


def bind(dag, sched):
    """Assign each op to a functional-unit instance. Greedy: inside a cycle, pick the free
    instance (and, for commutative ops, operand order) that adds the fewest new mux inputs.
    Returns (fu_of, fu_list): fu_of[idx] = (name, kind, swap); fu_list = ordered FU names."""
    L = max(sched.values())
    need = {k: 0 for k in PFX}
    for c in range(1, L + 1):
        for k in PFX:
            need[k] = max(need[k], sum(1 for o in dag.ops if sched[o.idx] == c and o.kind == k))
    srcs = defaultdict(lambda: (set(), set()))
    fu_of = {}
    for c in range(1, L + 1):
        for k in PFX:
            free = set(range(need[k]))
            for o in [o for o in dag.ops if sched[o.idx] == c and o.kind == k]:
                best = None
                for inst in sorted(free):
                    sa, sb = srcs[(k, inst)]
                    for swap in ((False, True) if k in COMMUTATIVE else (False,)):
                        a, b = (o.b, o.a) if swap else (o.a, o.b)
                        cost = (a not in sa) + (b not in sb)
                        if best is None or cost < best[0]:
                            best = (cost, inst, swap)
                _, inst, swap = best
                free.discard(inst)
                a, b = (o.b, o.a) if swap else (o.a, o.b)
                srcs[(k, inst)][0].add(a)
                srcs[(k, inst)][1].add(b)
                fu_of[o.idx] = (f"{PFX[k]}{inst}", k, swap)
    fu_list = [f"{PFX[k]}{i}" for k in PFX for i in range(need[k])]
    return fu_of, fu_list


def _src(tok):
    return tok if is_const(tok) else f"r_{tok}"


def reference(ops, inputs, vals, width):
    """Python golden model. Returns {ssa_name: value} including inputs."""
    m = (1 << width) - 1
    env = dict(zip(inputs, vals))
    get = lambda t: int(t) & m if is_const(t) else env[t]
    for o in ops:
        a, b = get(o.a), get(o.b)
        env[o.dest] = ((a + b) if o.kind == '+' else (a - b) if o.kind == '-' else (a * b)) & m
    return env


def view_names(ops, inputs):
    return list(inputs) + [o.dest for o in ops]


def switch_map(ops, inputs, fu_of, fu_list, sched):
    lines = ["SW[15:12] = functional-unit observe select (shown on 7-seg digits 3..0)"]
    for i, f in enumerate(fu_list[:MAXSW]):
        users = [o.dest for o in ops if fu_of[o.idx][0] == f]
        lines.append(f"  {i:2d} (0x{i:X}) : {f:5s} computes {', '.join(users)}")
    lines.append("SW[11:8]  = variable select: load target when IDLE, and register view (digits 7..4)")
    for i, n in enumerate(view_names(ops, inputs)[:MAXSW]):
        kind = "input " if n in inputs else f"cycle {sched[next(o.idx for o in ops if o.dest == n)]}"
        lines.append(f"  {i:2d} (0x{i:X}) : {n:8s} ({kind})")
    return "\n".join(lines) + "\n"


def emit_core(ops, inputs, dag, sched, width, defaults, name="hls_core"):
    L = max(sched.values())
    fu_of, fu_list = bind(dag, sched)
    names = view_names(ops, inputs)
    if len(names) > MAXSW:
        print(f"warning: {len(names)} variables but only {MAXSW} fit on the 4 select switches; "
              f"extra ones cannot be viewed/loaded from the board")
    if len(fu_list) > MAXSW:
        print(f"warning: {len(fu_list)} FUs but only {MAXSW} selectable on switches")
    v = []
    w = v.append
    w("// AUTO-GENERATED by hls.py -- do not edit by hand")
    w("`timescale 1ns/1ps   // same as the testbenches (Vivado xsim needs all or none)")
    w(f"// schedule length: {L} cycles | FUs: {', '.join(fu_list)}")
    for c in range(1, L + 1):
        w("//   cycle %d: %s" % (c, ", ".join(f"{o.dest}={o.a}{o.kind}{o.b}" for o in ops if sched[o.idx] == c)))
    w(f"module {name} #(parameter W = {width}) (")
    w("    input  wire clk, rst,")
    w("    input  wire step,                 // one-cycle pulse: advance the FSM")
    w("    input  wire load,                 // one-cycle pulse: write load_val into input load_idx (IDLE only)")
    w("    input  wire [3:0] load_idx,")
    w("    input  wire [W-1:0] load_val,")
    w("    input  wire [3:0] fu_sel,         // which functional unit to observe")
    w("    input  wire [3:0] var_sel,        // which variable register to observe")
    w("    output wire [4:0] state_out,")
    w("    output wire done,")
    w("    output reg  [W-1:0] fu_out,")
    w("    output reg  [W-1:0] var_out")
    w(");")
    w(f"    localparam [4:0] IDLE = 5'd0, DONE = 5'd{L + 1};")
    w("    reg [4:0] state;")
    w("    assign state_out = state;")
    w("    assign done = (state == DONE);")
    w("")
    w("    // ---------------- FSM: one state per scheduled cycle ----------------")
    w("    always @(posedge clk) begin")
    w("        if (rst)       state <= IDLE;")
    w("        else if (step) state <= (state == DONE) ? IDLE : state + 5'd1;")
    w("    end")
    w("")
    w("    // ---------------- registers ----------------")
    for n in inputs:
        w(f"    reg [W-1:0] r_{n};   // primary input")
    for o in ops:
        w(f"    reg [W-1:0] r_{o.dest};   // result of cycle {sched[o.idx]}")
    w("")
    w("    // input registers: reset to demo defaults, loadable from switches while IDLE")
    w("    always @(posedge clk) begin")
    w("        if (rst) begin")
    for n in inputs:
        w(f"            r_{n} <= {defaults[n]};")
    w("        end else if (load && state == IDLE) begin")
    w("            case (load_idx)")
    for i, n in enumerate(inputs[:MAXSW]):
        w(f"                4'd{i}: r_{n} <= load_val;")
    w("                default: ;")
    w("            endcase")
    w("        end")
    w("    end")
    w("")
    # ---- mux network + FUs
    w("    // ---------------- functional units with per-state input muxes ----------------")
    fu_ops = defaultdict(list)
    for o in ops:
        fu_ops[fu_of[o.idx][0]].append(o)
    kind_of = {f: next(fu_of[o.idx][1] for o in fu_ops[f]) for f in fu_list}
    for f in fu_list:
        w(f"    reg  [W-1:0] {f}_a, {f}_b;")
        w(f"    wire [W-1:0] {f}_y;")
        w(f"    always @* begin")
        w(f"        {f}_a = {{W{{1'b0}}}}; {f}_b = {{W{{1'b0}}}};")
        w(f"        case (state)")
        for o in sorted(fu_ops[f], key=lambda o: sched[o.idx]):
            swap = fu_of[o.idx][2]
            a, b = (o.b, o.a) if swap else (o.a, o.b)
            w(f"            5'd{sched[o.idx]}: begin {f}_a = {_src(a)}; {f}_b = {_src(b)}; end   // {o.dest}")
        w(f"            default: ;")
        w(f"        endcase")
        w(f"    end")
        w(f"    {MOD[kind_of[f]]} #(.W(W)) u_{f} (.a({f}_a), .b({f}_b), .y({f}_y));")
        act = " || ".join(f"(state == 5'd{sched[o.idx]})" for o in fu_ops[f])
        w(f"    wire {f}_act = {act};")
        w(f"    reg  [W-1:0] {f}_hold;   // last value this FU produced (for observation)")
        w(f"    always @(posedge clk) if (rst) {f}_hold <= 0; else if (step && {f}_act) {f}_hold <= {f}_y;")
        w(f"    wire [W-1:0] {f}_view = {f}_act ? {f}_y : {f}_hold;")
        w("")
    # ---- write enables
    w("    // ---------------- result registers: written at the end of the op's cycle ----------------")
    w("    always @(posedge clk) begin")
    w("        if (rst) begin")
    for o in ops:
        w(f"            r_{o.dest} <= 0;")
    w("        end else if (step) begin")
    w("            case (state)")
    for c in range(1, L + 1):
        stmts = " ".join(f"r_{o.dest} <= {fu_of[o.idx][0]}_y;" for o in ops if sched[o.idx] == c)
        w(f"                5'd{c}: begin {stmts} end")
    w("                default: ;")
    w("            endcase")
    w("        end")
    w("    end")
    w("")
    w("    // ---------------- observation muxes ----------------")
    w("    always @* begin")
    w("        case (fu_sel)")
    for i, f in enumerate(fu_list[:MAXSW]):
        w(f"            4'd{i}: fu_out = {f}_view;")
    w("            default: fu_out = {W{1'b0}};")
    w("        endcase")
    w("        case (var_sel)")
    for i, n in enumerate(names[:MAXSW]):
        w(f"            4'd{i}: var_out = r_{n};")
    w("            default: var_out = {W{1'b0}};")
    w("        endcase")
    w("    end")
    w("endmodule")
    return "\n".join(v) + "\n", fu_of, fu_list


def emit_testbench(ops, inputs, sched, width, defaults, seed=551, nvec=4, dut="hls_core"):
    L = max(sched.values())
    names = view_names(ops, inputs)
    rng = random.Random(seed)
    m = (1 << width) - 1
    vecs = [[defaults[n] for n in inputs]]
    for _ in range(nvec - 1):
        vecs.append([rng.randrange(0, 256) for _ in inputs])   # switches are 8 bits wide
    t = []
    w = t.append
    w("`timescale 1ns/1ps")
    w("// AUTO-GENERATED self-checking testbench for the synthesized core")
    w("module tb_hls_core;")
    w(f"    parameter W = {width};")
    w("    reg clk = 0, rst = 1, step = 0, load = 0;")
    w("    reg [3:0] load_idx = 0, fu_sel = 0, var_sel = 0;")
    w("    reg [W-1:0] load_val = 0;")
    w("    wire [4:0] state; wire done; wire [W-1:0] fu_out, var_out;")
    w(f"    {dut} #(.W(W)) dut (.clk(clk), .rst(rst), .step(step), .load(load), .load_idx(load_idx),")
    w("        .load_val(load_val), .fu_sel(fu_sel), .var_sel(var_sel), .state_out(state), .done(done),")
    w("        .fu_out(fu_out), .var_out(var_out));")
    w("    always #5 clk = ~clk;")
    w("    integer errors = 0;")
    w("    task do_reset; begin rst = 1; repeat (2) @(posedge clk); #1 rst = 0; end endtask")
    w("    task do_step; begin @(negedge clk); step = 1; @(posedge clk); #1 step = 0; @(posedge clk); #1; end endtask")
    w("    task do_load(input [3:0] i, input [W-1:0] v);")
    w("        begin @(negedge clk); load_idx = i; load_val = v; load = 1; @(posedge clk); #1 load = 0; end")
    w("    endtask")
    w("    task check(input [W-1:0] got, input [W-1:0] exp, input [255:0] nm);")
    w("        begin if (got !== exp) begin errors = errors + 1;")
    w('            $display("FAIL %0s: got %0d expected %0d", nm, got, exp); end end')
    w("    endtask")
    w("    integer k;")
    w("    initial begin")
    for vi, vec in enumerate(vecs):
        env = reference_env(ops, inputs, vec, width)
        w(f"        // ---- vector {vi}: " + ("defaults (no loading)" if vi == 0 else "loaded from 'switches'"))
        w("        do_reset;")
        if vi:
            for i, n in enumerate(inputs[:MAXSW]):
                w(f"        do_load(4'd{i}, {vec[i]});")
        for _ in range(L + 1):
            w("        do_step;")
        w('        if (!done) begin errors = errors + 1; $display("FAIL: FSM not DONE"); end')
        for n in [o.dest for o in ops]:
            w(f'        check(dut.r_{n}, {env[n]}, "{n}");')
        for i, n in enumerate(names[:MAXSW]):
            w(f"        var_sel = 4'd{i}; #1 check(var_out, {env[n]}, \"view_{n}\");")
        w("        do_step;   // DONE -> IDLE")
        w('        if (state !== 5\'d0) begin errors = errors + 1; $display("FAIL: did not return to IDLE"); end')
    w('        if (errors == 0) $display("PASS: all %0d vectors correct", ' + str(len(vecs)) + ");")
    w('        else $display("FAILED with %0d errors", errors);')
    w("        $finish;")
    w("    end")
    w("endmodule")
    return "\n".join(t) + "\n"


def reference_env(ops, inputs, vals, width):
    return reference(ops, inputs, vals, width)

def emit_top_testbench(ops, inputs, sched, width, defaults, fu_of, fu_list, seed=551):
    """Board-level testbench (testbench.v): drives top.v only through its pins -- bouncy
    buttons and switches -- and checks the LEDs and the decoded 7-segment display."""
    L = max(sched.values())
    names = view_names(ops, inputs)
    rng = random.Random(seed)
    vecs = [[defaults[n] for n in inputs], [rng.randrange(0, 256) for _ in inputs]]
    t = []
    w = t.append
    w("`timescale 1ns/1ps")
    w("// AUTO-GENERATED by hls.py: board-level self-checking testbench for top.v")
    w("// Uses only the board pins: BTNC = step, BTNU = load, SW, LED, 7-segment display.")
    w("module testbench;")
    w(f"    parameter W = {width};")
    w("    reg clk = 0, resetn = 1, btnc = 0, btnu = 0;")
    w("    reg [15:0] sw = 0;")
    w("    wire [15:0] led; wire [7:0] an; wire ca, cb, cc, cd, ce, cf, cg, dp;")
    w("    top #(.W(W), .DEBOUNCE_CYCLES(4), .REFRESH_BITS(1)) dut (")
    w("        .CLK100MHZ(clk), .CPU_RESETN(resetn), .BTNC(btnc), .BTNU(btnu), .SW(sw), .LED(led),")
    w("        .CA(ca), .CB(cb), .CC(cc), .CD(cd), .CE(ce), .CF(cf), .CG(cg), .DP(dp), .AN(an));")
    w("    always #5 clk = ~clk;")
    w("")
    w("    // ---- read the multiplexed display the way a person would: one digit at a time ----")
    w("    function [3:0] hex_of(input [6:0] s);   // s = {g,f,e,d,c,b,a}, active low")
    w("        case (s)")
    for i, p in enumerate(["1000000", "1111001", "0100100", "0110000", "0011001", "0010010", "0000010",
                           "1111000", "0000000", "0010000", "0001000", "0000011", "1000110", "0100001",
                           "0000110", "0001110"]):
        w(f"            7'b{p}: hex_of = 4'h{i:X};")
    w("            default: hex_of = 4'hx;")
    w("        endcase")
    w("    endfunction")
    w("    reg [31:0] disp = 0;   // [31:16] = variable view, [15:0] = functional unit view")
    w("    integer d;")
    w("    always @(posedge clk)")
    w("        for (d = 0; d < 8; d = d + 1)")
    w("            if (!an[d]) disp[d*4 +: 4] <= hex_of({cg, cf, ce, cd, cc, cb, ca});")
    w("")
    w("    integer errors = 0, checks = 0;")
    w("    task press_step; begin   // bounce a little, then hold, then release")
    w("        btnc = 1; #7 btnc = 0; #13 btnc = 1; repeat (12) @(posedge clk);")
    w("        #1 btnc = 0; #9 btnc = 1; #6 btnc = 0; repeat (12) @(posedge clk); #1; end")
    w("    endtask")
    w("    task press_load; begin")
    w("        btnu = 1; #7 btnu = 0; #13 btnu = 1; repeat (12) @(posedge clk);")
    w("        #1 btnu = 0; repeat (12) @(posedge clk); #1; end")
    w("    endtask")
    w("    task do_reset; begin resetn = 0; repeat (4) @(posedge clk); #1 resetn = 1; repeat (4) @(posedge clk); #1; end endtask")
    w("    task show; begin repeat (40) @(posedge clk); #1; end endtask   // let the display scan all digits")
    w("    task check(input [31:0] got, input [31:0] exp, input [255:0] nm);")
    w("        begin checks = checks + 1; if (got !== exp) begin errors = errors + 1;")
    w('            $display("FAIL %0s: got %0d expected %0d", nm, got, exp); end end')
    w("    endtask")
    w("")
    w("    initial begin")
    for vi, vec in enumerate(vecs):
        env = reference(ops, inputs, vec, width)
        w(f"        // ================= run {vi}: " + ("reset defaults" if vi == 0 else "inputs loaded from SW[7:0] with BTNU")
          + " (" + ", ".join(f"{n}={x}" for n, x in zip(inputs, vec)) + ") =================")
        w("        do_reset;")
        w('        check(led[14], 1, "IDLE led after reset");')
        if vi:
            for i, n in enumerate(inputs[:MAXSW]):
                w(f"        sw[11:8] = 4'd{i}; sw[7:0] = 8'd{vec[i]}; repeat (4) @(posedge clk); press_load;   // {n}")
        for c in range(1, L + 1):
            w(f"        press_step;   // -> cycle {c}")
            w(f'        check(led[4:0], {c}, "state led");')
            for o in ops:
                if sched[o.idx] != c or fu_of[o.idx][0] not in fu_list[:MAXSW]:
                    continue
                fi = fu_list.index(fu_of[o.idx][0])
                w(f"        sw[15:12] = 4'd{fi}; show; check(disp[15:0], {env[o.dest] & 0xFFFF}, "
                  f"\"{fu_of[o.idx][0]} computing {o.dest}\");")
        w("        press_step;   // -> DONE")
        w('        check(led[15], 1, "DONE led");')
        for i, n in enumerate(names[:MAXSW]):
            w(f"        sw[11:8] = 4'd{i}; show; check(disp[31:16], {env[n] & 0xFFFF}, \"register {n}\");")
        if inputs:
            w(f"        sw[11:8] = 4'd0; sw[7:0] = 8'd{(vec[0] ^ 0xFF) & 0xFF}; repeat (4) @(posedge clk); press_load; show;")
            w(f'        check(disp[31:16], {env[inputs[0]] & 0xFFFF}, "LOAD ignored when not IDLE");')
        w("        press_step;   // DONE -> IDLE")
        w('        check(led[4:0], 0, "back to IDLE");')
    w('        if (errors == 0) $display("PASS: %0d board-level checks correct", checks);')
    w('        else $display("FAILED with %0d errors (of %0d checks)", errors, checks);')
    w("        $finish;")
    w("    end")
    w("endmodule")
    return "\n".join(t) + "\n"
